"""Тестові дані: 50 користувачів, 20 подій, реєстрації та відгуки.

Ідемпотентний: повторний запуск нічого не дублює

Запуск з кореня проєкту:
    python -m app.seed
    python -m app.seed --db eventhub_test
"""
import argparse
import logging
import random
from datetime import datetime, timedelta, timezone
from typing import Dict, List, Optional

from bson import ObjectId

from app.operations import EventHubOperations

logger = logging.getLogger(__name__)

N_USERS = 50
N_EVENTS = 20
N_COMPLETED = 8

CITIES = [
    ("Kyiv", "Ukraine", [30.5234, 50.4501]),
    ("Lviv", "Ukraine", [24.0297, 49.8397]),
    ("Odesa", "Ukraine", [30.7233, 46.4825]),
    ("Kharkiv", "Ukraine", [36.2304, 49.9935]),
    ("Warsaw", "Poland", [21.0122, 52.2297]),
    ("Berlin", "Germany", [13.4050, 52.5200]),
    ("New York", "USA", [-74.0060, 40.7128]),
]
INTERESTS = ["tech", "music", "sports", "ai", "cloud", "devops", "design", "startups"]
CATEGORIES = ["conference", "workshop", "meetup", "webinar"]
TAGS = ["ai", "cloud", "devops", "python", "mongodb", "security", "data", "frontend"]
TOPICS = ["AI Summit", "Cloud Day", "DevOps Meetup", "Python Workshop", "MongoDB Deep Dive",
          "Security Forum", "Data Talks", "Frontend Camp", "Startup Night", "UX Conference"]


def _seed_users(ops: EventHubOperations) -> List[ObjectId]:
    """Створити seed-користувачів (наявні за email пропускаються)."""
    ids = []
    for i in range(N_USERS):
        rng = random.Random(i)
        email = f"seed_user_{i:02d}@eventhub.test"
        existing = ops.users.find_one({"email": email}, {"_id": 1})
        if existing:
            ids.append(existing["_id"])
            continue
        city, country, coords = rng.choice(CITIES)
        ids.append(ops.create_user({
            "email": email,
            "password_hash": "seed_not_a_real_hash",
            "profile": {"name": f"Seed User {i:02d}", "age": rng.randint(18, 65),
                        "bio": "Generated by app/seed.py"},
            "address": {"city": city, "country": country, "coordinates": coords},
            "interests": rng.sample(INTERESTS, 3),
            "badges": [],
            "preferences": {"newsletter": rng.random() < 0.5,
                            "notifications": ["email"], "language": "uk"},
        }))
    return ids


def _seed_events(ops: EventHubOperations, user_ids: List[ObjectId]) -> List[ObjectId]:
    """Створити seed-події (наявні за назвою пропускаються)."""
    ids = []
    now = datetime.now(timezone.utc).replace(microsecond=0)
    for i in range(N_EVENTS):
        rng = random.Random(1000 + i)
        seed_key = f"seed-event-{i:02d}"
        existing = ops.events.find_one({"metadata.seed_key": seed_key}, {"_id": 1})
        if existing:
            ids.append(existing["_id"])
            continue
        city, country, coords = rng.choice(CITIES)
        completed = i < N_COMPLETED
        start = now + (timedelta(days=-rng.randint(10, 80)) if completed
                       else timedelta(days=rng.randint(5, 120)))
        regular = round(rng.uniform(20, 200), 2)
        total = rng.choice([15, 25, 40, 60])
        ids.append(ops.create_event({
            "title": f"{rng.choice(TOPICS)} {2025 + i % 2} #{i:02d}",
            "description": f"Seed event {i} in {city}",
            "category": rng.choice(CATEGORIES),
            "tags": rng.sample(TAGS, 3),
            "schedule": {"start_date": start, "end_date": start + timedelta(hours=8),
                         "timezone": "Europe/Kyiv"},
            "location": {"type": "venue", "venue": f"{city} Hall", "city": city,
                         "country": country, "coordinates": coords, "address": "Main st. 1"},
            "capacity": {"total": total},
            "pricing": {"is_free": i % 5 == 0, "early_bird_price": round(regular * 0.7, 2),
                        "regular_price": regular, "currency": "USD"},
            "organizer": {"user_id": user_ids[i % 5], "team": [user_ids[(i + 1) % 5]]},
            "metadata": {"seed_key": seed_key, "event_url": f"https://eventhub.test/e/{i}",
                         "recording_available": completed, "materials": []},
            "status": "completed" if completed else "published",
        }))
    return ids


def _seed_registrations_and_reviews(ops: EventHubOperations,
                                    user_ids: List[ObjectId],
                                    event_ids: List[ObjectId]) -> Dict[str, int]:
    """Зареєструвати користувачів на події та додати відгуки."""
    created = {"registrations": 0, "reviews": 0}
    for idx, event_id in enumerate(event_ids):
        rng = random.Random(2000 + idx)
        event = ops.events.find_one({"_id": event_id}, {"capacity": 1})
        n = min(event["capacity"]["total"], rng.randint(8, 20))
        attendees = rng.sample(user_ids, n)
        for user_id in attendees:
            if not ops.registrations.find_one({"event_id": event_id, "user_id": user_id}, {"_id": 1}):
                ops.register_user_for_event(user_id, event_id)
                created["registrations"] += 1

            review_rng = random.Random(f"review-{idx}-{user_id}")
            if idx < N_COMPLETED and review_rng.random() < 0.5:
                if not ops.reviews.find_one({"event_id": event_id, "user_id": user_id}, {"_id": 1}):
                    ops.create_review(user_id, event_id, review_rng.choice([3, 4, 4, 5, 5]),
                                      comment="Seed review", pros=["Speakers"], cons=[])
                    created["reviews"] += 1
    return created


def seed(db_name: Optional[str] = None, ops: Optional[EventHubOperations] = None) -> Dict[str, int]:
    """Заповнити базу тестовими даними. Повертає кількість створених документів."""
    ops = ops or EventHubOperations(db_name=db_name)
    user_ids = _seed_users(ops)
    event_ids = _seed_events(ops, user_ids)
    created = _seed_registrations_and_reviews(ops, user_ids, event_ids)
    summary = {
        "users": ops.users.count_documents({"email": {"$regex": "^seed_user_"}}),
        "events": ops.events.count_documents({"metadata.seed_key": {"$exists": True}}),
        "registrations": ops.registrations.count_documents({"event_id": {"$in": event_ids}}),
        "reviews": ops.reviews.count_documents({"event_id": {"$in": event_ids}}),
        "created_registrations": created["registrations"],
        "created_reviews": created["reviews"],
    }
    logger.info(f"Seed summary: {summary}")
    return summary


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Заповнити базу тестовими даними")
    parser.add_argument("--db", default=None, help="ім'я бази (за замовчуванням MONGO_DB з .env)")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO)
    print(seed(args.db))
